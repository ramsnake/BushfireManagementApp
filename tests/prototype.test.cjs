const {test}=require('node:test');
const assert=require('node:assert/strict');
const {chromium}=require('playwright');

test('record, validate, review, export, persist, mobile and offline workflows',async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',args:['--no-sandbox']});
 try {
  const context=await browser.newContext({acceptDownloads:true});
  const page=await context.newPage();const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:3000');
  await page.getByRole('heading',{name:'Every contribution counts.'}).waitFor();
  assert.equal(await page.locator('tbody tr').count(),4);
  await page.evaluate(async()=>{await navigator.serviceWorker.ready;if(!navigator.serviceWorker.controller)await new Promise(resolve=>navigator.serviceWorker.addEventListener('controllerchange',resolve,{once:true}));});
  await page.getByRole('button',{name:'Record activity',exact:false}).click();
  await page.getByLabel('Activity title').fill('Smoke test <incident>');
  await page.getByLabel('Location',{exact:true}).fill('Test location');
  await page.getByLabel('Start time').fill('14:00');
  await page.getByLabel('Finish time').fill('13:00');
  await page.getByRole('button',{name:'Submit for review'}).click();
  assert.match(await page.locator('#form-error').textContent(),/later than/);
  await page.getByLabel('Finish time').fill('16:00');
  await page.getByRole('button',{name:'Submit for review'}).click();
  assert.match(await page.locator('#form-error').textContent(),/at least one/);
  await page.getByLabel('Alex Morgan').check();
  await page.getByLabel('Sam Wilson').check();
  await page.getByRole('button',{name:'Submit for review'}).click();
  await page.waitForFunction(()=>!document.querySelector('#record-dialog').open);
  await page.reload();
  await page.getByRole('link',{name:'Activity records'}).click();
  await page.getByRole('textbox',{name:'Search activity records'}).fill('Smoke test');
  assert.equal(await page.locator('tbody tr').count(),1);
  await page.locator('.row-button').click();
  assert.match(await page.locator('#detail-content').textContent(),/4 combined · 2 per person/);
  await page.getByRole('button',{name:'Approve record'}).click();
  assert.match(await page.locator('tbody').textContent(),/Approved/);
  await page.locator('.row-button').click();
  assert.equal(await page.getByRole('button',{name:'Edit record'}).count(),0);
  await page.getByRole('button',{name:'Close',exact:true}).click();
  await page.getByRole('link',{name:'Members & hours'}).click();
  assert.match(await page.locator('.member-card').first().textContent(),/10\.3 hours/);
  await page.getByRole('link',{name:'Reports & exports'}).click();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:/Approved only/}).click();
  const download=await downloadPromise;const stream=await download.createReadStream();let csv='';for await(const chunk of stream)csv+=chunk;
  assert.match(csv,/Smoke test <incident>/);assert.doesNotMatch(csv,/Awaiting review|"Draft"|"Review"/);
  await context.setOffline(true);
  await page.reload();
  await page.getByRole('heading',{name:'Reports & exports'}).waitFor();
  assert.match(await page.locator('#connection').textContent(),/Offline/);
  await page.getByRole('link',{name:'Activity records'}).click();
  assert.match(await page.locator('tbody').textContent(),/Smoke test <incident>/);
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('link',{name:'Overview',exact:false}).click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'/tmp/brigade-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1100});
  await page.screenshot({path:'/tmp/brigade-desktop.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await context.close();
 }finally{await browser.close();}
});
